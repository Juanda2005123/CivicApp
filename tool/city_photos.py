"""Builds the photos of the city packs and their credits.

    python tool/city_photos.py        (needs Pillow: pip install pillow)

For every city in CITIES it reads the originals from
docs/design/ideas/city-identity/photos/, writes the WebP files of
assets/cities/<slug>/ (docs/design/04-city-identity.md, section 4) and rewrites
assets/cities/CREDITS.md from CREDITS.json with the photos in use. To add a
city, add its entry here with the photos chosen in the mockup and run it.
"""

import io
import json
from pathlib import Path

from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parent.parent
ORIGINALS = ROOT / "docs/design/ideas/city-identity/photos"
OUTPUT = ROOT / "assets/cities"

HERO_WIDTH = 1080
RANK_SIDE = 480
MAX_BYTES = 200 * 1000

# slug: (city name, header photos by moment of the day, rank photos in climbing order)
CITIES = {
    "cali": (
        "Cali",
        {
            "morning": "cali-centro-cristo",
            "afternoon": "cali-tres-cruces-lejos",
            "night": "cali-noche-oeste",
        },
        ["cali-gato", "cali-ermita", "cali-cristo-rey", "cali-tres-cruces-foto"],
    ),
    "medellin": (
        "Medellín",
        {
            "morning": "med-panoramica",
            "afternoon": "med-metrocable",
            "night": "med-noche",
        },
        ["med-comuna13", "med-botero", "med-metrocable", "med-pueblito"],
    ),
}


def load(credits: dict, key: str) -> Image.Image:
    image = Image.open(ORIGINALS / credits[key]["file"])
    return ImageOps.exif_transpose(image).convert("RGB")


def save_webp(image: Image.Image, target: Path) -> int:
    """Saves with the best quality that stays under MAX_BYTES."""
    for quality in range(82, 20, -4):
        buffer = io.BytesIO()
        image.save(buffer, "WEBP", quality=quality, method=6)
        if buffer.tell() < MAX_BYTES:
            target.write_bytes(buffer.getvalue())
            return buffer.tell()
    raise SystemExit(f"{target.name} does not fit in {MAX_BYTES} bytes")


def main() -> None:
    credits = json.loads((ORIGINALS / "CREDITS.json").read_text(encoding="utf-8"))
    lines = [
        "# City photo credits",
        "",
        "Generated by `python tool/city_photos.py`; do not edit by hand. Every photo comes",
        "from Wikimedia Commons under a free license, resized (and the rank ones cropped",
        "to a square). The app does not show them (academic project, decision of 2026-11-25).",
        "",
    ]

    for slug, (city, heroes, ranks) in CITIES.items():
        folder = OUTPUT / slug
        folder.mkdir(parents=True, exist_ok=True)
        used = []

        for part, key in heroes.items():
            image = load(credits, key)
            height = round(image.height * HERO_WIDTH / image.width)
            size = save_webp(image.resize((HERO_WIDTH, height), Image.LANCZOS), folder / f"hero_{part}.webp")
            used.append((f"hero_{part}.webp", key))
            print(f"{slug}/hero_{part}.webp  {size // 1000} KB")

        for index, key in enumerate(ranks, start=1):
            image = ImageOps.fit(load(credits, key), (RANK_SIDE, RANK_SIDE), Image.LANCZOS)
            size = save_webp(image, folder / f"rank_{index}.webp")
            used.append((f"rank_{index}.webp", key))
            print(f"{slug}/rank_{index}.webp  {size // 1000} KB")

        lines += [f"## {city}", "", "| File | Photo | Author | License |", "|---|---|---|---|"]
        for file, key in used:
            credit = credits[key]
            title = credit["title"].replace("|", "\\|")
            lines.append(
                f"| `{slug}/{file}` | [{title}]({credit['source']}) | "
                f"{credit['author'] or 'Unknown author'} | {credit['license']} |"
            )
        lines.append("")

    (OUTPUT / "CREDITS.md").write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print("assets/cities/CREDITS.md written")


if __name__ == "__main__":
    main()
