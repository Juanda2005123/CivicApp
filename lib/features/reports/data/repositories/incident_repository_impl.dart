import 'package:vigia_app/features/auth/domain/entities/coordinates.dart';
import '../../domain/entities/feed_incident.dart';
import '../../domain/entities/incident.dart';
import '../../domain/entities/incident_photo.dart';
import '../../domain/entities/incident_marker.dart';
import '../../domain/entities/nearby_incident.dart';
import '../../domain/entities/picked_photo.dart';
import '../../domain/repositories/incident_repository.dart';
import '../datasources/incident_remote_data_source.dart';
import '../datasources/photo_storage_data_source.dart';
import '../models/incident_model.dart';

/// Implements [IncidentRepository] orchestrating PostgREST data and Storage uploads.
class IncidentRepositoryImpl implements IncidentRepository {
  final IncidentRemoteDataSource _remoteDataSource;
  final PhotoStorageDataSource _storageDataSource;

  IncidentRepositoryImpl(
    this._remoteDataSource,
    this._storageDataSource,
  );

  @override
  Future<Incident> createIncident({
    required String reporterId,
    required int categoryId,
    required String title,
    required String description,
    required IncidentSeverity severity,
    String? estimatedDimensions,
    required Coordinates coordinates,
    required String formattedAddress,
    required String neighborhood,
    required String city,
    required List<PickedPhoto> photos,
  }) async {
    // 1. Upload photos to storage first
    final List<String> uploadedUrls = [];
    for (final photo in photos) {
      final url = await _storageDataSource.uploadPhoto(
        bytes: photo.bytes,
        extension: photo.extension,
        reporterId: reporterId,
      );
      uploadedUrls.add(url);
    }

    // 2. Prepare model with generated civic tracking code
    final trackingCode = IncidentRemoteDataSource.generateTrackingCode();
    final modelToInsert = IncidentModel(
      id: '', // Generated by PostgreSQL UUID
      trackingCode: trackingCode,
      reporterId: reporterId,
      categoryId: categoryId,
      title: title,
      description: description,
      severity: severity,
      status: IncidentStatus.reported,
      estimatedDimensions: estimatedDimensions,
      coordinates: coordinates,
      formattedAddress: formattedAddress,
      neighborhood: neighborhood,
      city: city,
      createdAt: DateTime.now(),
    );

    // 3. Persist record and photo linkages
    return _remoteDataSource.insertIncident(
      incident: modelToInsert,
      photoUrls: uploadedUrls,
    );
  }

  @override
  Future<List<NearbyIncident>> getNearbyIncidents({
    required Coordinates coordinates,
    required int categoryId,
    double radiusInMeters = 150.0,
  }) {
    return _remoteDataSource.getNearbyIncidents(
      latitude: coordinates.latitude,
      longitude: coordinates.longitude,
      categoryId: categoryId,
      radiusInMeters: radiusInMeters,
    );
  }

  @override
  Future<List<IncidentMarker>> getCityIncidents(String city) {
    return _remoteDataSource.getCityIncidents(city);
  }

  @override
  Future<List<FeedIncident>> getCityFeed(String city, {required int offset, int limit = 20}) {
    return _remoteDataSource.getCityFeed(city, offset: offset, limit: limit);
  }

  @override
  Future<Incident> getIncidentById(String idOrTrackingCode) {
    return _remoteDataSource.getIncidentById(idOrTrackingCode);
  }

  @override
  Future<Incident> updateIncident({
    required String incidentId,
    required String reporterId,
    required int categoryId,
    required String title,
    required String description,
    required IncidentSeverity severity,
    String? estimatedDimensions,
    required List<IncidentPhoto> removedPhotos,
    required List<PickedPhoto> addedPhotos,
  }) async {
    // The text first: it is the step the server may refuse (window over or 5
    // endorsements), and then nothing was uploaded for nothing.
    await _remoteDataSource.updateIncidentRow(
      incidentId: incidentId,
      categoryId: categoryId,
      title: title,
      description: description,
      severity: severity,
      estimatedDimensions: estimatedDimensions,
    );

    if (removedPhotos.isNotEmpty || addedPhotos.isNotEmpty) {
      try {
        final uploadedUrls = <String>[];
        for (final photo in addedPhotos) {
          uploadedUrls.add(await _storageDataSource.uploadPhoto(
            bytes: photo.bytes,
            extension: photo.extension,
            reporterId: reporterId,
          ));
        }
        await _remoteDataSource.replacePhotos(
          incidentId: incidentId,
          removedPhotoIds: removedPhotos.map((photo) => photo.id).toList(),
          newPhotoUrls: uploadedUrls,
        );
      } on Exception catch (e) {
        final reason = e.toString().replaceFirst('Exception: ', '');
        throw Exception('Guardamos los cambios del texto, pero no pudimos actualizar las fotos. $reason');
      }
    }

    return _remoteDataSource.getIncidentById(incidentId);
  }

  @override
  Future<void> deleteIncident(Incident incident) => _remoteDataSource.deleteIncident(incident.id);

  @override
  Future<void> endorseIncident({
    required String incidentId,
    required String userId,
  }) {
    return _remoteDataSource.endorseIncident(
      incidentId: incidentId,
      userId: userId,
    );
  }

  @override
  Future<void> revokeEndorsement({
    required String incidentId,
    required String userId,
  }) {
    return _remoteDataSource.revokeEndorsement(
      incidentId: incidentId,
      userId: userId,
    );
  }
}
